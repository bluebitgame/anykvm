"""Precompile D3D11 JPEG and RemoteFX shaders with Windows SDK FXC."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import tempfile
import time

import build_shaders


SOURCE = build_shaders.JPEG_SOURCE
# Package-level headers are inputs to Go's CGO build cache. Keeping generated
# DXBC here makes a changed artifact invalidate cached C objects as well.
OUTPUT = SOURCE.parent.parent / "jpeg420_dxbc.h"
BUILD_TAG = "d3d11_precompiled"
ENTRIES = ("selectEntropy", "prepareEntropy", "prepareWork", "compareTiles", "main",
           "encodeMCUs", "indexSegments", "scanSegmentGroups", "addSegmentOffsets", "packJPEG")
PROFILE = "cs_5_0"
FLAGS = ("/O3", "/Ges")
VERSION = 1


def shader_jobs():
    gpuconv = build_shaders.ROOT / "internal/gpuconv"
    return (
        ("JPEG", SOURCE, OUTPUT, ENTRIES, "bk_jpeg"),
        ("RemoteFX Progressive", build_shaders.PROGRESSIVE_SOURCE, gpuconv / "progressive_dxbc.h",
         ("main", "encodeTiles", "indexSegments", "packSegments"), "bk_progressive"),
        ("RemoteFX surface", build_shaders.PROGRESSIVE_SURFACE_SOURCE, gpuconv / "progressive_surface_dxbc.h",
         ("main",), "bk_progressive_surface"),
    )


def find_fxc():
    override = os.environ.get("FXC")
    if override:
        compiler = shutil.which(override)
        if not compiler:
            raise ValueError(f"FXC compiler not found: {override}")
        return compiler
    compiler = shutil.which("fxc.exe")
    if compiler:
        return compiler
    # SDK tools run on the build host, independently of the Go target CPU.
    machine = platform.machine().lower()
    arches = ("arm64", "x64", "x86") if machine in ("arm64", "aarch64") else ("x64", "x86")
    bins = []
    if os.environ.get("WindowsSdkVerBinPath"):
        bins.append(Path(os.environ["WindowsSdkVerBinPath"]))
    roots = [Path(os.environ[name]) / "bin" for name in ("WindowsSdkDir",) if os.environ.get(name)]
    for name in ("ProgramFiles(x86)", "ProgramFiles"):
        if os.environ.get(name):
            roots.append(Path(os.environ[name]) / "Windows Kits/10/bin")
    for root in roots:
        versions = [path for path in root.glob("10.*") if path.is_dir()
                    and all(part.isdigit() for part in path.name.split("."))]
        bins.extend(sorted(versions, key=lambda path: tuple(map(int, path.name.split("."))), reverse=True))
        bins.append(root)
    for directory in bins:
        for arch in arches:
            compiler = directory / arch / "fxc.exe"
            if compiler.is_file():
                return str(compiler)
    raise ValueError("Windows SDK FXC not found; install the Windows SDK shader tools "
                     "or set FXC to the full path of fxc.exe")


def settings(source, entries=ENTRIES, prefix="bk_jpeg"):
    return {"version": VERSION, "source_sha256": hashlib.sha256(source).hexdigest(),
            "profile": PROFILE, "flags": list(FLAGS), "entries": list(entries), "prefix": prefix}


def current(source, output=None, entries=ENTRIES, prefix="bk_jpeg"):
    output = OUTPUT if output is None else output
    try:
        manifest = json.loads(output.with_suffix(".json").read_text(encoding="utf-8"))
        return (all(manifest.get(key) == value for key, value in settings(source, entries, prefix).items())
                and manifest["header_sha256"] == hashlib.sha256(output.read_bytes()).hexdigest())
    except (OSError, ValueError, KeyError, TypeError, AttributeError):
        return False


def header(stages, prefix="bk_jpeg"):
    guard = "ANYKVM_" + prefix.upper() + "_DXBC_H"
    lines = ["/* Generated by tools/build_dxbc.py; do not edit. */",
             "#ifndef " + guard, "#define " + guard]
    for index, (_, code) in enumerate(stages):
        lines.append(f"static const unsigned char {prefix}_dxbc_{index}[] = {{")
        for start in range(0, len(code), 16):
            lines.append("    " + ",".join(f"0x{value:02x}" for value in code[start:start + 16]) + ",")
        lines.append("};")
    lines += ["typedef struct {", "    const char *entry;", "    const unsigned char *bytes;",
              "    size_t size;", f"}} {prefix}_dxbc_stage;",
              f"static const {prefix}_dxbc_stage {prefix}_dxbc_stages[] = {{"]
    for index, (entry, _) in enumerate(stages):
        lines.append(f'    {{"{entry}", {prefix}_dxbc_{index}, sizeof({prefix}_dxbc_{index})}},')
    lines += ["};", "#endif", ""]
    return "\n".join(lines).encode("ascii")


def prepare(compiler=None, dry_run=False):
    for job in shader_jobs():
        prepare_shader(*job, compiler=compiler, dry_run=dry_run)


def prepare_shader(label, source_path, output_path, entries, prefix, compiler=None, dry_run=False):
    source = build_shaders.shader_source(source_path)
    if compiler is None and current(source, output_path, entries, prefix):
        return
    if dry_run:
        print(f"  Would precompile {len(entries)} D3D11 {label} shaders with Windows SDK FXC and embed DXBC.")
        return
    compiler = compiler or find_fxc()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    # Keep the last complete bundle on compiler failure. A partial publication
    # cannot pass the next build's source/settings/header checksum validation.
    with tempfile.TemporaryDirectory(prefix=".dxbc-", dir=output_path.parent) as temporary:
        directory = Path(temporary)
        hlsl = directory / source_path.name
        hlsl.write_bytes(source)
        stages = []
        for index, entry in enumerate(entries, 1):
            output = directory / f"{entry}.dxbc"
            print(f"  FXC {label} [{index}/{len(entries)}] {entry}: compile started", flush=True)
            started = time.monotonic()
            subprocess.run([str(compiler), "/nologo", "/T", PROFILE, "/E", entry, *FLAGS,
                            "/Fo", str(output), str(hlsl)], check=True)
            code = output.read_bytes()
            if len(code) < 32 or code[:4] != b"DXBC":
                raise ValueError(f"FXC did not produce DXBC for {label}/{entry}")
            stages.append((entry, code))
            print(f"  FXC {label} [{index}/{len(entries)}] {entry}: finished in "
                  f"{time.monotonic() - started:.3f}s ({len(code)} bytes)", flush=True)
        data = header(stages, prefix)
        manifest = settings(source, entries, prefix)
        manifest["header_sha256"] = hashlib.sha256(data).hexdigest()
        staged_header = directory / output_path.name
        staged_header.write_bytes(data)
        staged_manifest = directory / output_path.with_suffix(".json").name
        staged_manifest.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        os.replace(staged_header, output_path)
        os.replace(staged_manifest, output_path.with_suffix(".json"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", help="path to Windows SDK fxc.exe; forces recompilation")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    try:
        prepare(args.compiler, args.dry_run)
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        parser.exit(1, f"DXBC preparation failed: {exc}\n")


if __name__ == "__main__":
    main()
