// hidModifierMask returns the CGEventFlags mask bit for a modifier HID keycode,
// or 0 if the keycode is not a modifier. Used to maintain the event flags so
// injected key events carry the correct modifier state.
func hidModifierMask(code uint8) uint64 {
	switch code {
	case 0xE0, 0xE4: // Control
		return cgFlagControl
	case 0xE1, 0xE5: // Shift
		return cgFlagShift
	case 0xE2, 0xE6: // Option/Alt
		return cgFlagOption
	case 0xE3, 0xE7: // Command/GUI
		return cgFlagCommand
	}
	return 0
}

// CGEventFlags bits (from CoreGraphics CGEventTypes.h).
const (
	cgFlagShift   = 1 << 17 // kCGEventFlagMaskShift
	cgFlagControl = 1 << 18 // kCGEventFlagMaskControl
	cgFlagOption  = 1 << 19 // kCGEventFlagMaskAlternate
	cgFlagCommand = 1 << 20 // kCGEventFlagMaskCommand
)
